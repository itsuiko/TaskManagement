-- 最初の1回だけ入る、使い方の見本（サンプル）6件。
--
-- ■ tasks が0件のときだけ入れる（末尾の WHERE NOT EXISTS）
--
-- spring.sql.init.mode=always はこのファイルを「起動のたびに実行する」設定なので、
-- 条件を付けずに INSERT を書くと起動のたびに6件ずつ増える（第10回に実際に踏んだ）。
--
-- 以前は先頭に DELETE FROM tasks を置いて「全部消してから入れ直す」形で重複を避けていたが、
-- それだと **バックエンドを起動し直すたびに、画面から登録したタスクまで全部消える**。
-- 完了条件 #12「バックエンドを再起動してから開く → タスクがすべて残っている」
-- （docs/requirements.md 7章）を満たしていなかったので、第15回の品質チェックで直した。
--
-- いまは「1件でも入っていれば何もしない」。サンプルは入ったあと、画面から登録したタスクと
-- 同じ扱いになる（編集も削除もできる。起動し直しても元の内容には戻らない）。
-- タイトルの【サンプル】は、自分で登録したものと見分けるための印。
--
-- ⚠️ 自分で全部消してから起動し直すと、0件なのでサンプルがもう一度入る。
--
-- ■ id は書かない
--
-- 書くと自動採番のシーケンスとずれて、後から API 経由で登録したときに主キーの衝突が起きる。
--
-- ■ created_at / updated_at / status は明示的に入れる
--
-- これらの既定値は DB の DEFAULT 制約ではなくエンティティ側（Task.java）で与えているため、
-- SQL から直接 INSERT すると効かない。docs/data-design.md 3章に書いたとおり。
--
-- ■ 期限は固定の日付ではなく「起動した日から数えて何日後」
--
-- 固定の日付を書くと、日が経つにつれて全部が期限切れの見本になる。

INSERT INTO tasks (title, description, due_date, priority, status, sort_order, created_at, updated_at)
SELECT v.title, v.description, v.due_date, v.priority, v.status, v.sort_order, now(), now()
FROM (VALUES
	('【サンプル】カードをクリックすると編集できます', 'タイトル・説明文・期限・優先度を直して「保存」を押します。この6枚は使い方の見本です。不要になったら消してください。', CURRENT_DATE + 7, 'medium', 'todo', 1),
	('【サンプル】カードをドラッグすると別の列へ移せます', '掴んだまま「作業中」や「完了」の上で離します。移したカードは、その列の一番下に入ります。', NULL, 'low', 'todo', 2),
	('【サンプル】列の下の「＋ カードを追加」で新しく作れます', '必須なのはタイトルだけです。3つの列のどこからでも追加できます。', NULL, NULL, 'todo', 3),
	('【サンプル】期限と優先度はカードに表示されます', '優先度は 高・中・低 の3段階です。期限も優先度も、未指定のままにできます。', CURRENT_DATE + 3, 'high', 'doing', 1),
	('【サンプル】編集画面の「状態」からも列を移せます', 'ドラッグを使わず、キーボードだけで移動したいときに使います。', NULL, NULL, 'doing', 2),
	('【サンプル】不要なカードは編集画面の「削除」で消せます', '削除すると元に戻せません。終わったタスクは消さずに「完了」へ移しておくと、やったことが残ります。', NULL, 'low', 'done', 1)
) AS v(title, description, due_date, priority, status, sort_order)
WHERE NOT EXISTS (SELECT 1 FROM tasks);
